# 2.1 Frey Face Dataset Loading
class FreyFaceDataset(Dataset):
    def __init__(self, file_path, transform=None):
        mat = scipy.io.loadmat(file_path)
        # Data is in shape (1965, 560), needs to be (1965, 28, 20)
        self.data = mat['ff'].T.reshape((-1, 28, 20))
        self.transform = transform

    def __len__(self):
        return len(self.data)

    def __getitem__(self, idx):
        sample = self.data[idx]
        # Convert to float32 and scale to [0, 1]
        sample = sample.astype(np.float32) / 255.0
        if self.transform:
            sample = self.transform(sample)
        return sample, 0 # Return 0 as a dummy label

# 2.2 VAE Model Architecture
class VAE(nn.Module):
    def __init__(self, input_dim=28*20, hidden_dim=200, latent_dim=20):
        super(VAE, self).__init__()
        self.input_dim = input_dim
        # Encoder
        self.encoder = nn.Sequential(
            nn.Linear(input_dim, hidden_dim),
            nn.ReLU(),
            nn.Linear(hidden_dim, hidden_dim//2),
            nn.ReLU(),
        )
        self.fc_mu = nn.Linear(hidden_dim//2, latent_dim)
        self.fc_log_var = nn.Linear(hidden_dim//2, latent_dim)

        # Decoder
        self.decoder = nn.Sequential(
            nn.Linear(latent_dim, hidden_dim//2),
            nn.ReLU(),
            nn.Linear(hidden_dim//2, hidden_dim),
            nn.ReLU(),
            nn.Linear(hidden_dim, input_dim),
            nn.Sigmoid() # Sigmoid for output in range [0, 1]
        )

    def encode(self, x):
        h = self.encoder(x)
        return self.fc_mu(h), self.fc_log_var(h)

    def reparameterize(self, mu, log_var):
        std = torch.exp(0.5 * log_var)
        eps = torch.randn_like(std)
        return mu + eps * std

    def decode(self, z):
        return self.decoder(z)

    def forward(self, x):
        mu, log_var = self.encode(x.view(-1, self.input_dim))
        z = self.reparameterize(mu, log_var)
        return self.decode(z), mu, log_var

# 2.3 VAE Loss Function and Training
def vae_loss_function(recon_x, x, mu, log_var):
    # Use Binary Cross-Entropy for reconstruction loss for sigmoid output
    BCE = nn.functional.binary_cross_entropy(recon_x, x.view(-1, 28*20), reduction='sum')
    # KL divergence loss
    KLD = -0.5 * torch.sum(1 + log_var - mu.pow(2) - log_var.exp())
    return BCE + KLD

def train_vae(model, dataloader, epochs=50, learning_rate=1e-3):
    optimizer = optim.Adam(model.parameters(), lr=learning_rate)
    model.train()
    print("--- Training Variational Autoencoder ---")
    for epoch in range(epochs):
        total_loss = 0
        for data, _ in dataloader:
            data = data.to(device)
            optimizer.zero_grad()
            recon_batch, mu, log_var = model(data)
            loss = vae_loss_function(recon_batch, data, mu, log_var)
            loss.backward()
            total_loss += loss.item()
            optimizer.step()

        print(f'Epoch [{epoch+1}/{epochs}], Loss: {total_loss / len(dataloader.dataset):.4f}')
    print("--- VAE Training Finished ---")
    return model

# 2.4 VAE Evaluation (Sampling from Latent Space)
def sample_from_vae(model, num_samples=20, latent_dim=20):
    print("--- Sampling from VAE Latent Space ---")
    model.eval()
    with torch.no_grad():
        # Generate random samples from the latent space (prior distribution)
        z = torch.randn(num_samples, latent_dim).to(device)
        samples = model.decode(z).cpu()

    # Plot the generated samples
    fig, axes = plt.subplots(4, 5, figsize=(8, 8))
    for i, ax in enumerate(axes.flat):
        ax.imshow(samples[i].view(28, 20), cmap='gray')
        ax.axis('off')
    plt.suptitle('Random Samples from VAE Latent Space')
    plt.savefig('results/vae_random_samples.png')
    plt.show()

