# 1.2 Model Architecture (U-Net style without skip connections)
class Autoencoder(nn.Module):
    def __init__(self, embedding_dim=64):
        super(Autoencoder, self).__init__()
        # Encoder
        self.encoder = nn.Sequential(
            nn.Linear(28 * 28, 512),
            nn.ReLU(True),
            nn.Linear(512, 256),
            nn.ReLU(True),
            nn.Linear(256, 128),
            nn.ReLU(True),
            nn.Linear(128, embedding_dim) # This is our embedding h
        )
        # Decoder
        self.decoder = nn.Sequential(
            nn.Linear(embedding_dim, 128),
            nn.ReLU(True),
            nn.Linear(128, 256),
            nn.ReLU(True),
            nn.Linear(256, 512),
            nn.ReLU(True),
            nn.Linear(512, 28 * 28),
            nn.Tanh() # Tanh activation to match the normalized input range [-1, 1]
        )

    def forward(self, x):
        h = self.encoder(x)
        x_hat = self.decoder(h)
        return x_hat, h

# 1.3 Loss Functions and Training Loops

# Reconstruction Loss
reconstruction_loss_fn = nn.MSELoss()

# Sparsity Penalty (KL Divergence)
def kl_divergence(rho, rho_hat):
    rho_hat = torch.mean(torch.sigmoid(rho_hat), 1) # Average activation for each neuron
    rho = torch.tensor([rho] * len(rho_hat)).to(device)
    return torch.sum(rho * torch.log(rho/rho_hat) + (1-rho) * torch.log((1-rho)/(1-rho_hat)))

# Training function for Sparse Autoencoder
def train_sparse_ae(model, dataloader, epochs=20, learning_rate=1e-3, sparsity_param=0.05, sparsity_weight=1e-4):
    optimizer = optim.Adam(model.parameters(), lr=learning_rate)
    model.train()
    print("--- Training Sparse Autoencoder ---")
    for epoch in range(epochs):
        total_loss = 0
        for data in dataloader:
            img, _ = data
            img = img.view(img.size(0), -1).to(device)

            # Forward pass
            output, hidden = model(img)

            # Calculate losses
            recon_loss = reconstruction_loss_fn(output, img)
            sparsity_loss = kl_divergence(sparsity_param, hidden)
            loss = recon_loss + sparsity_weight * sparsity_loss

            # Backward pass and optimization
            optimizer.zero_grad()
            loss.backward()
            optimizer.step()
            total_loss += loss.item()

        print(f'Epoch [{epoch+1}/{epochs}], Loss: {total_loss/len(dataloader):.4f}')
    print("--- Sparse Autoencoder Training Finished ---")
    return model

# Training function for Contractive Autoencoder
def train_contractive_ae(model, dataloader, epochs=20, learning_rate=1e-3, contractive_weight=1e-4):
    optimizer = optim.Adam(model.parameters(), lr=learning_rate)
    model.train()
    print("--- Training Contractive Autoencoder ---")
    for epoch in range(epochs):
        total_loss = 0
        for data in dataloader:
            img, _ = data
            img = img.view(img.size(0), -1).to(device)
            img.requires_grad = True # We need gradients with respect to the input

            # Forward pass
            output, hidden = model(img)

            # Calculate reconstruction loss
            recon_loss = reconstruction_loss_fn(output, img)

            # Calculate contractive penalty
            # We need the Jacobian of the hidden layer with respect to the input
            J = torch.autograd.grad(hidden, img, grad_outputs=torch.ones_like(hidden), create_graph=True)[0]
            contractive_loss = torch.sum(J ** 2)

            loss = recon_loss + contractive_weight * contractive_loss

            # Backward pass and optimization
            optimizer.zero_grad()
            loss.backward()
            optimizer.step()
            total_loss += loss.item()

        print(f'Epoch [{epoch+1}/{epochs}], Loss: {total_loss/len(dataloader):.4f}')
    print("--- Contractive Autoencoder Training Finished ---")
    return model

